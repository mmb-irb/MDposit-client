import { MMCIF, PDB, getStructureFormat } from '.';

describe('getStructureFormat', () => {
  it('finds PDB files', () => {
    expect(getStructureFormat('ATOM      1  N   ALA A   1       0.000   0.000   0.000\nEND\n')).toBe(PDB);
    expect(getStructureFormat('REMARK 1 generated\nCRYST1  10.000  10.000  10.000\n')).toBe(PDB);
  });

  it('finds mmCIF files', () => {
    expect(getStructureFormat('data_1ABC\n#\nloop_\n_atom_site.group_PDB\n')).toBe(MMCIF);
  });

  // mmCIF comments start with '#', so they must not be read as a PDB record
  it('skips empty lines and comments before the mmCIF block header', () => {
    expect(getStructureFormat('\n# Generated by MDDB\n\r\ndata_structure\n')).toBe(MMCIF);
  });

  it('fails with an empty structure', () => {
    expect(() => getStructureFormat('\n  \n')).toThrow('The structure is empty');
  });
});
